// site.config.json -> src/text/site.generated.js
import { readFileSync, writeFileSync } from "node:fs";

const site = JSON.parse(readFileSync("site.config.json", "utf8"));
for (const k of ["name", "app", "copyrightYear", "copyrightHolder", "copyrightUrl", "repository"]) {
  if (typeof site[k] !== "string" || !site[k]) throw new Error(`site.config.json: missing "${k}"`);
}
const holder = `${site.copyrightYear} ${site.copyrightHolder} (${site.copyrightUrl.replace(/^https?:\/\//, "")})`;
writeFileSync("src/text/site.generated.js",
  `// SPDX-FileCopyrightText: ${holder}\n// SPDX-License-Identifier: AGPL-3.0-only\n` +
  `// GENERATED by scripts/build.mjs from site.config.json. Do not edit by hand.\n` +
  `export const SITE = ${JSON.stringify(site, null, 2)};\n`);
console.log("src/text/site.generated.js written");
