// Measure advance widths of printable ASCII in bold sans and serif faces, as fractions of 1em.
// Liberation Sans and Serif share metrics with Arial and Times New Roman, so text drawn with
// "Arial, Liberation Sans, Helvetica" lines up the same on Windows, macOS and Linux.
// Output: src/text/metrics.generated.js. Requires ImageMagick.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const PT = 1000;
const magick = (argv) => {
  for (const bin of ["magick", "convert"]) {
    try { return execFileSync(bin, argv).toString(); } catch (e) { if (e.code !== "ENOENT") throw e; }
  }
  throw new Error("ImageMagick not found");
};
const width = (font, text) => +magick(["-font", font, "-pointsize", String(PT), `label:${text}`, "-format", "%w", "info:"]);
const escape = (s) => s.replace(/\\/g, "\\\\").replace(/^@/, "\\@").replace(/%/g, "%%");

const out = {};
for (const [key, font] of [["sans", "Liberation-Sans-Bold"], ["serif", "Liberation-Serif-Bold"]]) {
  const hh = width(font, "HH");
  const w = [];
  for (let c = 32; c <= 126; c++) w.push(Math.round(((width(font, escape(`H${String.fromCharCode(c)}H`)) - hh) / PT) * 1000) / 1000);
  out[key] = w;
  console.log(key, "measured", w.length, "glyphs; 'a' =", w[97 - 32]);
}
writeFileSync("src/text/metrics.generated.js",
  `// SPDX-FileCopyrightText: 2026 Aesthetic Vulpes (github.com/didvc)\n// SPDX-License-Identifier: AGPL-3.0-only\n` +
  `// GENERATED by scripts/build-metrics.mjs: advance widths (em) for chars 32..126, bold weight.\n` +
  `export const METRICS = ${JSON.stringify(out)};\n`);
